BEGIN;

CREATE SCHEMA IF NOT EXISTS restaurant;

CREATE TABLE restaurant.customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(100)
);

CREATE TABLE restaurant.employee (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    role VARCHAR(50) NOT NULL
        CHECK (role IN ('Manager', 'Host', 'Server', 'Cashier')),
    phone VARCHAR(20)
);

CREATE TABLE restaurant.restaurant_table (
    table_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number INTEGER NOT NULL UNIQUE CHECK (table_number > 0),
    seating_capacity INTEGER NOT NULL CHECK (seating_capacity > 0),
    status VARCHAR(30) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available', 'Occupied', 'Reserved'))
);

CREATE TABLE restaurant.menu_category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL,
    description TEXT
);

CREATE TABLE restaurant.menu_item (
    menu_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL,
    item_name VARCHAR(100) NOT NULL,
    description TEXT,
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    availability_status VARCHAR(30) NOT NULL DEFAULT 'Available'
        CHECK (availability_status IN ('Available', 'Unavailable')),

    -- Keep a category while menu items reference it.
    -- Propagate a corrected category ID to its menu items.
    CONSTRAINT fk_menu_item_category
        FOREIGN KEY (category_id)
        REFERENCES restaurant.menu_category(category_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE restaurant.restaurant_order (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    employee_id INTEGER NOT NULL,
    table_id INTEGER NOT NULL,
    order_datetime TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'Draft'
        CHECK (status IN ('Draft', 'Open', 'Preparing', 'Served',
                         'Completed', 'Cancelled')),

    -- Preserve customer attribution for existing orders.
    -- Propagate a corrected customer ID.
    CONSTRAINT fk_order_customer
        FOREIGN KEY (customer_id)
        REFERENCES restaurant.customer(customer_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    -- Preserve the employee responsible for existing orders.
    -- Propagate a corrected employee ID.
    CONSTRAINT fk_order_employee
        FOREIGN KEY (employee_id)
        REFERENCES restaurant.employee(employee_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    -- Preserve the seating reference in order history.
    -- Propagate a corrected table ID.
    CONSTRAINT fk_order_table
        FOREIGN KEY (table_id)
        REFERENCES restaurant.restaurant_table(table_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE restaurant.order_item (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    menu_item_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),

    -- Prevent deleting an order while its item records exist.
    -- Propagate a corrected order ID.
    CONSTRAINT fk_order_item_order
        FOREIGN KEY (order_id)
        REFERENCES restaurant.restaurant_order(order_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    -- Preserve menu item references in historical sales.
    -- Mark discontinued items Unavailable instead of deleting them.
    -- Propagate a corrected menu item ID.
    CONSTRAINT fk_order_item_menu_item
        FOREIGN KEY (menu_item_id)
        REFERENCES restaurant.menu_item(menu_item_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE restaurant.payment (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    payment_datetime TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    payment_method VARCHAR(50) NOT NULL
        CHECK (payment_method IN ('Cash', 'Card', 'Digital Wallet')),
    payment_status VARCHAR(30) NOT NULL DEFAULT 'Pending'
        CHECK (payment_status IN ('Pending', 'Completed', 'Failed', 'Refunded')),

    -- Prevent deleting an order while payment records reference it.
    -- Propagate a corrected order ID to its payments.
    CONSTRAINT fk_payment_order
        FOREIGN KEY (order_id)
        REFERENCES restaurant.restaurant_order(order_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- BCNF: do not store calculated line_total or total_amount.
-- Calculate line_total as quantity * unit_price.
-- Calculate total_amount by summing line totals for an order.
-- unit_price preserves the price agreed at the time of sale.
--
-- A confirmed order must have at least one item.
-- This cross-table rule requires transaction-level validation;
-- the foreign keys above do not enforce a minimum item count.

COMMIT;
